use crate::com::error::model::ComError;
use crate::com::handshake::{
    derive_session_key, CHALLENGE_PLAINTEXT_LEN, ECIES_CIPHERTEXT_LEN, HANDSHAKE_MESSAGE_MAX,
    PUBLIC_KEY_LEN, SIGNATURE_LEN,
};
use crate::models::common::{
    BodySchema, Destination::{AllGateways, OneDestination}, MessageSchema, MessageType,
    RequestType, ResponseType, deserialize_clear,
};
use bincode::{Decode, Encode};
use embedded_hal::delay::DelayNs;
use embedded_hal::digital::OutputPin;
use embedded_hal::spi::SpiBus;
use lora;

/// Step 1 message broadcast by the sensor to all gateways.
///
/// Carries the sensor's identity proof (`sensor_pubkey` + `sig_sensor_pubkey`) so
/// the gateway can verify the sensor **before** sending the challenge.
/// The sensor MAC is not included here — it is already present in `header.src`.
#[derive(Encode, Decode, Debug, Clone, PartialEq, Eq)]
pub struct HandshakeRequest {
    /// Random nonce generated by the sensor. The gateway must sign this to prove
    /// possession of its private key.
    sensor_nonce: [u8; 32],
    /// Sensor's P-256 compressed public key.
    sensor_pubkey: [u8; PUBLIC_KEY_LEN],
    /// Sensor's ECDSA signature of its own public key (binds the public key to the private key).
    sig_sensor_pubkey: [u8; SIGNATURE_LEN],
}

impl HandshakeRequest {
    pub fn new(
        sensor_nonce: [u8; 32],
        sensor_pubkey: [u8; PUBLIC_KEY_LEN],
        sig_sensor_pubkey: [u8; SIGNATURE_LEN],
    ) -> Self {
        Self {
            sensor_nonce,
            sensor_pubkey,
            sig_sensor_pubkey,
        }
    }

    pub fn sensor_nonce(&self) -> &[u8; 32] {
        &self.sensor_nonce
    }

    pub fn sensor_pubkey(&self) -> &[u8; PUBLIC_KEY_LEN] {
        &self.sensor_pubkey
    }

    pub fn sig_sensor_pubkey(&self) -> &[u8; SIGNATURE_LEN] {
        &self.sig_sensor_pubkey
    }
}

/// Step 3 confirmation sent by the sensor to the gateway.
///
/// The sensor proves liveness by signing the gateway's nonce. The sensor's public key
/// identity was already established in `HandshakeRequest`.
#[derive(Encode, Decode, Debug, Clone, PartialEq, Eq)]
pub struct HandshakeConfirm {
    sig_gateway_nonce: [u8; SIGNATURE_LEN],
}

impl HandshakeConfirm {
    pub fn new(sig_gateway_nonce: [u8; SIGNATURE_LEN]) -> Self {
        Self { sig_gateway_nonce }
    }

    /// Returns the sensor's ECDSA signature of the gateway nonce.
    pub fn sig_gateway_nonce(&self) -> &[u8; SIGNATURE_LEN] {
        &self.sig_gateway_nonce
    }
}

/// Sensor-side handshake: performs the full 3-message ECDH authenticated key exchange.
///
/// 1. Broadcasts `HandshakeRequest` (sensor_nonce + sensor_pubkey + sig_sensor_pubkey).
/// 2. Waits for `HandshakeChallenge` (ECIES-encrypted by the gateway for this sensor).
/// 3. Decrypts the challenge, verifies the gateway's signature of the sensor nonce.
/// 4. Signs the gateway nonce via `sign_gateway_nonce` callback.
/// 5. Sends `HandshakeConfirm` (sig_gateway_nonce) back to the gateway.
/// 6. Derives `session_key = HKDF-SHA256(ecdh_shared_secret, sensor_nonce || gateway_nonce)`.
///
/// Returns the 32-byte session key on success.
///
/// # Callbacks
/// - `ecies_decrypt`: decrypts the 190-byte ECIES ciphertext using the sensor's private key.
///   Writes the 129-byte plaintext to `out`. Returns the ECDH shared secret, or `Err(())` on failure.
/// - `verify_sig_sensor_nonce`: verifies `(gateway_pubkey, sig_sensor_nonce)`. Returns `false`
///   to reject the challenge (causes `Err(ComError::VerificationFailed)`).
/// - `sign_gateway_nonce`: signs the 32-byte gateway nonce with the sensor's private key.
///   Returns the 64-byte ECDSA signature.
///
/// # Errors
/// - `Err(ComError::VerificationFailed)` if the gateway's signature check fails.
/// - `Err(ComError::Timeout)` if no valid `HandshakeChallenge` is received.
#[allow(clippy::too_many_arguments)]
pub fn initiate_handshake<SPI, CS, RST, SpiErr, FD, FV, FS>(
    lora: &mut lora::sx1278::Controller<SPI, CS, RST>,
    delay: &mut impl DelayNs,
    sensor_mac: [u8; 17],
    battery_level: u8,
    sensor_nonce: [u8; 32],
    sensor_pubkey: [u8; PUBLIC_KEY_LEN],
    sig_sensor_pubkey: [u8; SIGNATURE_LEN],
    ecies_decrypt: FD,
    verify_sig_sensor_nonce: FV,
    sign_gateway_nonce: FS,
    timestamp: u32,
) -> Result<[u8; 32], ComError<SpiErr>>
where
    SPI: SpiBus<u8, Error = SpiErr>,
    CS: OutputPin,
    RST: OutputPin,
    FD: Fn(
        &[u8; ECIES_CIPHERTEXT_LEN],
        &mut [u8; CHALLENGE_PLAINTEXT_LEN],
    ) -> Result<[u8; 32], ()>,
    FV: Fn(&[u8; PUBLIC_KEY_LEN], &[u8; SIGNATURE_LEN]) -> bool,
    FS: Fn(&[u8; 32]) -> [u8; SIGNATURE_LEN],
{
    let rx_timeout = 4;

    // Step 1: broadcast HandshakeRequest
    let mut msg = MessageSchema::create_body_request(
        sensor_mac,
        battery_level,
        AllGateways,
        MessageType::HandshakeRequest,
        RequestType::HandshakeRequest(HandshakeRequest {
            sensor_nonce,
            sensor_pubkey,
            sig_sensor_pubkey,
        }),
        timestamp,
    );
    let buffer = msg
        .serialize_clear::<HANDSHAKE_MESSAGE_MAX>()
        .map_err(ComError::Custom)?;
    lora.set_mode(lora::sx1278::Mode::Manual, delay);
    lora.send(&buffer, delay)?;
    lora.set_mode(lora::sx1278::Mode::Receiver, delay);

    // Step 2: wait for HandshakeChallenge
    let mut recv_buffer = [0u8; HANDSHAKE_MESSAGE_MAX];
    for _ in 0..rx_timeout {
        let receive_result =
            if let Ok(r) = lora.receive::<SpiErr, _>(&mut recv_buffer, delay) {
                r
            } else {
                delay.delay_ms(5000u32);
                continue;
            };

        let clear_msg = match deserialize_clear::<HANDSHAKE_MESSAGE_MAX>(
            &recv_buffer[..receive_result.size],
        ) {
            Ok(m) => m,
            Err(_) => continue,
        };

        if clear_msg.header.message_type != MessageType::HandshakeChallenge {
            continue;
        }
        if clear_msg.header.dist != OneDestination(sensor_mac) {
            continue;
        }

        let ciphertext =
            if let BodySchema::ResponseType(ResponseType::HandshakeChallenge(c)) = &clear_msg.body
            {
                c.data
            } else {
                continue;
            };

        // ECIES decrypt: caller uses own private key
        let mut plaintext = [0u8; CHALLENGE_PLAINTEXT_LEN];
        let shared_secret = match ecies_decrypt(&ciphertext, &mut plaintext) {
            Ok(s) => s,
            Err(_) => continue,
        };

        // Parse plaintext: sig_sensor_nonce[64] | gateway_pubkey[33] | gateway_nonce[32]
        let sig_sensor_nonce: [u8; SIGNATURE_LEN] =
            plaintext[..SIGNATURE_LEN].try_into().unwrap();
        let gateway_pubkey: [u8; PUBLIC_KEY_LEN] = plaintext
            [SIGNATURE_LEN..SIGNATURE_LEN + PUBLIC_KEY_LEN]
            .try_into()
            .unwrap();
        let gateway_nonce: [u8; 32] =
            plaintext[SIGNATURE_LEN + PUBLIC_KEY_LEN..].try_into().unwrap();

        // Verify gateway signed our nonce
        if !verify_sig_sensor_nonce(&gateway_pubkey, &sig_sensor_nonce) {
            return Err(ComError::VerificationFailed);
        }

        // Step 3: sign gateway nonce, send HandshakeConfirm
        let sig_gw_nonce = sign_gateway_nonce(&gateway_nonce);
        let gateway_mac = clear_msg.header.src;

        let mut confirm_msg = MessageSchema::create_body_request(
            sensor_mac,
            battery_level,
            OneDestination(gateway_mac),
            MessageType::HandshakeConfirm,
            RequestType::HandshakeConfirm(HandshakeConfirm {
                sig_gateway_nonce: sig_gw_nonce,
            }),
            timestamp,
        );
        let confirm_buffer = confirm_msg
            .serialize_clear::<HANDSHAKE_MESSAGE_MAX>()
            .map_err(ComError::Custom)?;
        lora.set_mode(lora::sx1278::Mode::Manual, delay);
        lora.send(&confirm_buffer, delay)?;

        // Derive session key from ECDH shared secret + both nonces
        return Ok(derive_session_key(&shared_secret, &sensor_nonce, &gateway_nonce));
    }

    Err(ComError::Timeout)
}

